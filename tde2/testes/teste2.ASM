POSICIONA_JIPE proc
    mov JIPE_X, ax
    mov JIPE_ALT, 0
    mov SALTO_FASE, SALTO_CHAO
    mov SALTO_PX, 0
    ret
POSICIONA_JIPE endp

; Funcao: perder uma vida e reaparecer com protecao temporaria.
; Entrada: VIDAS maior que zero.
; Saida: VIDAS reduzida; se restarem vidas, jipe volta a coluna zero.
PERDE_VIDA proc
    dec VIDAS
    jz perde_fim
    mov ax, X_RETORNO_JIPE
    call POSICIONA_JIPE
    mov IMUNIDADE, DURACAO_IMUNIDADE
perde_fim:
    ret
PERDE_VIDA endp

; Funcao: marcar como livres os slots de uma categoria.
