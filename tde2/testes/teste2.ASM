ANIMA_MENU endp

; Funcao: consultar e consumir uma tecla na fila da BIOS.
; Entrada: nenhuma.
; Saida: CF=1 sem tecla; CF=0 com AL ASCII e AH scan code.
LE_TECLA proc
    mov ah, 01h
    int 16h
    jz tecla_ausente
    xor ah, ah
    int 16h
    clc
    ret
tecla_ausente:
    stc
    ret
LE_TECLA endp

