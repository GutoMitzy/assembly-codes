; Funcao: atualizar tempo e protecao em ticks reais da BIOS.
; Entrada: referencia anterior CX:DX guardada nas variaveis de tick.
; Saida: TEMPO_RESTANTE, referencia e IMUNIDADE atualizados.
ATUALIZA_TEMPO proc
    xor ah, ah
    int 1Ah
    mov bx, dx
    mov si, cx
    sub dx, TICK_ANT_BAIXO
    sbb cx, TICK_ANT_ALTO
    jnc tempo_delta
    add dx, TICKS_DIA_BAIXO
    adc cx, TICKS_DIA_ALTO
tempo_delta:
    mov TICK_ANT_BAIXO, bx
    mov TICK_ANT_ALTO, si
    or cx, cx
    jnz tempo_esgotado
    sub IMUNIDADE, dx
    jnc tempo_imune_pronto
    mov IMUNIDADE, 0
tempo_imune_pronto:
    add TICK_ACUM, dx
    jc tempo_esgotado
tempo_ajusta:
    mov bx, TICKS_SEGUNDO
    cmp FRACAO_SEGUNDO, CICLO_FRACAO - 1
    jne tempo_limite
    inc bx
tempo_limite:
    cmp TICK_ACUM, bx
    jb tempo_fim
    sub TICK_ACUM, bx
    inc FRACAO_SEGUNDO
    cmp FRACAO_SEGUNDO, CICLO_FRACAO
    jb tempo_segundo
    mov FRACAO_SEGUNDO, 0
tempo_segundo:
    dec TEMPO_RESTANTE
    jnz tempo_ajusta
tempo_esgotado:
    mov TEMPO_RESTANTE, 0
tempo_fim:
    ret
ATUALIZA_TEMPO endp

; Funcao: consumir a fila do jogo e aplicar as teclas de movimento.
; Entrada: fila BIOS, JIPE_X, SALTO_FASE.
; Saida: posicao, salto ou disparo atualizados; ENCERROU em caso de Esc.
ENTRADA_JOGO proc
entrada_laco:
    call LE_TECLA
    jc entrada_fim
    cmp al, TECLA_ESC
    jne entrada_disparo
    mov ENCERROU, 1
    ret
entrada_disparo:
    cmp al, TECLA_ESPACO
    jne entrada_salto
    call DISPARAR
    jmp entrada_laco
entrada_salto:
    cmp ah, SCAN_CIMA
    jne entrada_lateral
    cmp SALTO_FASE, SALTO_CHAO
    jne entrada_laco
    mov SALTO_FASE, SALTO_SOBE
    jmp entrada_laco
entrada_lateral:
    mov bx, JIPE_PASSO_ESQ
    cmp ah, SCAN_ESQUERDA
    je entrada_move
    mov bx, JIPE_PASSO_DIR
    cmp ah, SCAN_DIREITA
    jne entrada_laco
entrada_move:
    add bx, JIPE_X
    jns entrada_limita
    xor bx, bx
entrada_limita:
    cmp bx, X_MAX_JIPE
    jle entrada_grava
    mov bx, X_MAX_JIPE
entrada_grava:
    mov JIPE_X, bx
    jmp entrada_laco
entrada_fim:
    ret
ENTRADA_JOGO endp

; Funcao: atualizar o salto em tres fases, com um patamar no topo.
; Entrada: SALTO_FASE, JIPE_ALT e SALTO_PX.
; Saida: fase e altura do quadro atual; altera AX.
ATUALIZA_SALTO proc
    cmp SALTO_FASE, SALTO_CHAO
    je salto_fim
    cmp SALTO_FASE, SALTO_TOPO
    je salto_patamar
    ja salto_descida
    mov ax, JIPE_ALT
    add ax, SALTO_VEL
    cmp ax, SALTO_ALTURA
    jl salto_grava
    mov ax, SALTO_ALTURA
    mov SALTO_FASE, SALTO_TOPO
    mov SALTO_PX, 0
    jmp salto_grava
salto_patamar:
    add SALTO_PX, VEL_CHAO
    cmp SALTO_PX, SALTO_TOPO_PX
    jb salto_fim
    mov SALTO_FASE, SALTO_DESCE
    ret
salto_descida:
    mov ax, JIPE_ALT
    sub ax, SALTO_VEL
    jg salto_grava
    xor ax, ax
    mov SALTO_FASE, SALTO_CHAO
salto_grava:
    mov JIPE_ALT, ax
salto_fim:
    ret
ATUALIZA_SALTO endp

; Funcao: reposicionar o jipe no solo.
