; Funcao: recortar um intervalo na horizontal.
; Entrada: AX X com sinal, CX largura.
; Saida: AX X visivel, CX largura visivel; CX=0 sem pixels.
RECORTA_X proc
    push BX

    cmp AX, 0
    jge recorta_dir          ; X ja visivel
    mov BX, AX
    neg BX                   ; BX = colunas cortadas a esquerda
    cmp BX, CX
    jae recorta_nada         ; tudo fora pela esquerda
    sub CX, BX
    xor AX, AX               ; primeira coluna visivel = 0

recorta_dir:
    mov BX, LARG_TELA
    sub BX, AX               ; BX = colunas ate a borda direita
    jle recorta_nada         ; tudo fora pela direita
    cmp CX, BX
    jbe recorta_fim
    mov CX, BX               ; corta excesso a direita

recorta_fim:
    pop BX
    ret

recorta_nada:
    xor CX, CX
    jmp recorta_fim
RECORTA_X endp

; Funcao: buscar um caractere na fonte.
; Entrada: AL caractere ASCII.
; Saida: AL indice do glifo ou espaco.
ASCII_PARA_INDICE proc
    push BX
    push CX

    cmp AL, 'a'              ; minuscula -> maiuscula
    jb  procura
    cmp AL, 'z'
    ja  procura
    sub AL, 20H

procura:
    mov BX, offset FONTE_CHARS
    mov CX, NUM_GLYPHS

procura_loop:
    cmp AL, [BX]
    je  achou
    inc BX
    loop procura_loop

    mov AL, G_ESPACO         ; nao existe: usa espaco
    jmp fim_conversao

achou:
    sub BX, offset FONTE_CHARS
    mov AL, BL                ; AL = indice do glifo

fim_conversao:
    pop CX
    pop BX
    ret
ASCII_PARA_INDICE endp

; Funcao: desenhar glifo 5x8 em uma area contida no quadro.
; Entrada: AL indice, DS:DI paleta, ASCII_X/Y, ES quadro.
; Saida: Glifo transparente composto; preserva registradores.
