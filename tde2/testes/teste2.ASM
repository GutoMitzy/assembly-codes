; Funcao: acionar os canhoes frontal e superior do jipe.
; Entrada: JIPE_X e JIPE_ALT.
; Saida: tiros disponiveis iniciados; altera AX, DX e SI.
DISPARAR proc
    mov si, offset TIRO_CIMA
    mov ax, JIPE_X
    add ax, CANHAO_CIMA_X
    mov dx, JIPE_Y - ALT_TIRO_CIMA
    sub dx, JIPE_ALT
    call INICIA_TIRO
    mov si, offset TIRO_FRENTE
    cmp word ptr [si + T_ATIVO], 0
    jne dispara_fim
    mov ax, JIPE_X
    add ax, LARGURA_JIPE + CANHAO_FRENTE_FOLGA
    mov dx, JIPE_Y + CANHAO_FRENTE_Y
    sub dx, JIPE_ALT
    call INICIA_TIRO
    add ax, ALCANCE_TIRO
    mov [si + T_LIM], ax
dispara_fim:
    ret
DISPARAR endp

; Funcao: disparar para baixo a partir de cada nave totalmente visivel.
; Entrada: listas de naves e tiros.
; Saida: um tiro ativo por slot livre de nave; altera AX, DX, BX e SI.
ATIRA_ALIENS proc
    xor bx, bx
    mov si, offset TIROS_ALIENS
atira_slot:
    cmp ALIENS_ATIVO[bx], 0
    je atira_prox
    mov ax, ALIENS_X[bx]
    cmp ax, 0
    jl atira_prox
    cmp ax, LARG_TELA - LARGURA_NAVE
    jg atira_prox
    add ax, (LARGURA_NAVE - LARG_TIRO_ALIEN) / 2
    mov dx, ALIENS_Y[bx]
    add dx, ALTURA_NAVE + FOLGA_TIRO_ALIEN
    call INICIA_TIRO
atira_prox:
    add bx, 2
    add si, TAM_TIRO
    cmp bx, NUM_ALIENS * 2
    jb atira_slot
    ret
ATIRA_ALIENS endp

; Funcao: mover um projetil e descarta-lo ao atingir seu limite.
; Entrada: DS:SI tiro, com T_LIM exclusivo no eixo de deslocamento.
; Saida: coordenadas e flag de atividade atualizadas; altera AX.
ATUALIZA_TIRO proc
    cmp word ptr [si + T_ATIVO], 0
    je tiro_mov_fim
    mov ax, [si + T_DX]
    add [si + T_X], ax
    or ax, ax
    jz tiro_mov_y
    mov ax, [si + T_X]
    cmp ax, [si + T_LIM]
    jge tiro_mov_desliga
    cmp ax, LARG_TELA
    jge tiro_mov_desliga
    ret

tiro_mov_y:
    mov ax, [si + T_DY]
    add [si + T_Y], ax
    or ax, ax
    js tiro_mov_cima
    mov ax, [si + T_Y]
    cmp ax, [si + T_LIM]
    jge tiro_mov_desliga
    ret
tiro_mov_cima:
    mov ax, [si + T_Y]
    cmp ax, [si + T_LIM]
    jge tiro_mov_fim
tiro_mov_desliga:
    mov word ptr [si + T_ATIVO], 0
tiro_mov_fim:
    ret
ATUALIZA_TIRO endp

; Funcao: compor um tiro como retangulo solido com recorte horizontal.
; Entrada: DS:SI tiro, ES quadro. O movimento ja limitou o intervalo Y.
; Saida: pixels visiveis compostos; preserva SI.
DESENHA_TIRO proc
    cmp word ptr [si + T_ATIVO], 0
    je desenha_tiro_fim
