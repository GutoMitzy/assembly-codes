    push AX
    push BX
    push CX
    push DX
    push SI
    push DI
    push BP

    xor AH, AH
    mov BX, ALTURA
    mul BX                   ; cada glifo tem uma linha por byte
    mov SI, offset FONTE_GLYPHS
    add SI, AX               ; SI = bytes do glifo

    mov AX, ASCII_Y
    mov BX, LARG_TELA
    mul BX                   ; AX = Y * 320
    add AX, ASCII_X
    mov BH, [DI + 1]         ; BH = cor (entrada 1 da paleta)
    mov DI, AX               ; DI = offset na VRAM

    mov AL, BH               ; AL = cor (para stosb)
    mov BP, ALTURA           ; 8 linhas

proxima_linha:
    mov BL, [SI]             ; BL = bitmap da linha
    inc SI
    mov CX, LARGURA          ; 5 colunas

proximo_pixel:
    test BL, 10H             ; bit 4 = pixel mais a esquerda
    jz   pixel_vazio
    stosb                    ; pinta
    jmp  proximo_bit

pixel_vazio:
    inc DI                   ; pula sem pintar

proximo_bit:
    shl BL, 1
    loop proximo_pixel

    add DI, LARG_TELA - LARGURA
    dec BP
    jnz proxima_linha

    pop BP
    pop DI
    pop SI
    pop DX
    pop CX
    pop BX
    pop AX
    ret
DESENHA_CARACTERE endp

; Funcao: desenhar texto terminado em zero, com suporte a CR/LF.
; Entrada: DS:SI texto, DS:DI paleta, CX/DX avancos, ASCII_X/Y.
; Saida: ASCII_X/Y seguem a ultima posicao; preserva registradores.
ESCREVER_TEXTO proc
    push AX
    push BX
    push SI

    mov BX, ASCII_X          ; BX = X inicial (restaurado em LF)

texto_exibe:
    lodsb
    cmp AL, 0
    je  texto_fim
    cmp AL, ASCII_CR               ; CR: ignora
    je  texto_exibe
    cmp AL, ASCII_LF               ; LF: proxima linha
    je  texto_nova_linha

    call ASCII_PARA_INDICE
    call DESENHA_CARACTERE
    add ASCII_X, CX
    jmp texto_exibe

texto_nova_linha:
    mov ASCII_X, BX
    add ASCII_Y, DX
    jmp texto_exibe

texto_fim:
    pop SI
    pop BX
    pop AX
    ret
ESCREVER_TEXTO endp

; Funcao: desenhar moldura com glifos horizontais e verticais.
; Entrada: CX largura interna positiva, DS:DI paleta, ASCII_X/Y.
; Saida: Moldura composta e coordenadas preservadas.
DESENHAR_CAIXA proc
    push AX
    push BX
    push CX
    push DX
    push SI
    push BP

    mov SI, ASCII_X
    mov DX, CX               ; DX = repeticoes do meio
    mov BX, offset CAIXA_GLIFOS
    mov BP, CAIXA_LINHAS                ; 3 linhas

caixa_linha:
    mov AL, [BX]
    call DESENHA_CARACTERE
    add ASCII_X, LARGURA

    mov AL, [BX + 1]
    mov CX, DX
caixa_meio:
    call DESENHA_CARACTERE
    add ASCII_X, LARGURA
    loop caixa_meio

    mov AL, [BX + 2]
    call DESENHA_CARACTERE

    mov ASCII_X, SI
    add ASCII_Y, ALTURA
    add BX, CAIXA_LINHAS
    dec BP
    jnz caixa_linha

    sub ASCII_Y, CAIXA_LINHAS * ALTURA  ; restaura Y inicial
    pop BP
    pop SI
    pop DX
    pop CX
    pop BX
    pop AX
    ret
DESENHAR_CAIXA endp

; Funcao: gerar valor pseudoaleatorio por xorshift de 16 bits.
; Entrada: CX faixa positiva, SEMENTE diferente de zero.
; Saida: AX em 0..CX-1; atualiza SEMENTE.
ALEATORIO proc
    push DX
    push CX

    mov AX, SEMENTE
    mov DX, AX
    mov CL, 7
    shl DX, CL
    xor AX, DX               ; x ^= x << 7
    mov DX, AX
    mov CL, 9
    shr DX, CL
    xor AX, DX               ; x ^= x >> 9
    mov DX, AX
    mov CL, 8
    shl DX, CL
    xor AX, DX               ; x ^= x << 8
    mov SEMENTE, AX

    pop CX
    xor DX, DX
    div CX                   ; DX = AX mod CX
    mov AX, DX

    pop DX
    ret
ALEATORIO endp

; Funcao: desenhar sprite indexado transparente, recortando as duas dimensoes.
; Entrada: DS:SI pixels ASCII, DS:BX paleta, CX largura, DX altura, ASCII_X/Y.
; Saida: pixels em ES; preserva registradores e coordenadas.
DESENHA_SPRITE proc
    push ax
    push bx
    push cx
    push dx
    push si
    push di
    push bp
    jcxz sprite_fim
    or dx, dx
    jz sprite_fim
    mov bp, cx
    mov ax, ASCII_X
    call RECORTA_X
    jcxz sprite_fim
    mov di, ax
    sub ax, ASCII_X
    add si, ax
    mov ax, ASCII_Y

sprite_linha:
    cmp ax, ALT_TELA
    jge sprite_fim
    or ax, ax
    js sprite_avanca
    push ax
    push dx
    push cx
    push si
    push di
    mov dx, LARG_TELA
    mul dx
    add di, ax
sprite_pixel:
    lodsb
    sub al, '0'
    jz sprite_transparente
    xlat
    stosb
    jmp sprite_proximo
sprite_transparente:
    inc di
sprite_proximo:
    loop sprite_pixel
    pop di
    pop si
    pop cx
    pop dx
    pop ax
sprite_avanca:
    add si, bp
    inc ax
    dec dx
    jnz sprite_linha
sprite_fim:
    pop bp
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    pop ax
    ret
DESENHA_SPRITE endp

; Funcao: preencher um retangulo inteiramente contido no quadro.
; Entrada: AL cor, CX largura, DX altura, ASCII_X/Y, ES quadro.
; Saida: retangulo preenchido; preserva registradores.
PREENCHER_LINHAS proc
    push AX
    push BX
    push CX
    push DX
    push SI
    push DI

    mov SI, DX               ; SI = contador de linhas (mul sobrescreve DX)
    cmp SI, 0
    je  preencher_fim

    mov BH, AL               ; guarda a cor
    mov AX, ASCII_Y
    mov DX, LARG_TELA
    mul DX                   ; AX = Y * 320
    add AX, ASCII_X
    mov DI, AX               ; DI = offset inicial na VRAM
    mov AL, BH
    mov BX, CX               ; BX = largura (preservada entre linhas)

preencher_linha:
    mov CX, BX
    rep stosb                ; pinta a linha
    add DI, LARG_TELA        ; desce uma linha
    sub DI, BX               ; volta ao X inicial
    dec SI
    jnz preencher_linha

preencher_fim:
    pop DI
    pop SI
    pop DX
    pop CX
    pop BX
    pop AX
    ret
PREENCHER_LINHAS endp

; Funcao: limpar apenas o quadro de trabalho em RAM.
; Entrada: ES quadro.
; Saida: quadro preto; altera AX, CX e DI.
LIMPAR_QUADRO proc
    xor di, di
    xor ax, ax
    mov cx, TAM_TELA
    rep stosb
    ret
LIMPAR_QUADRO endp

; Funcao: apresentar o quadro pronto no inicio do retraco vertical.
; Entrada: ES quadro, DF=0.
; Saida: quadro copiado para A000h; preserva DS e ES.
APRESENTA proc
    mov dx, PORTA_VGA
ap_sai:
    in al, dx
    test al, BIT_RETRACO
    jnz ap_sai
ap_entra:
    in al, dx
    test al, BIT_RETRACO
    jz ap_entra
    push ds
    push es
    push es
    pop ds
    mov ax, SEG_VGA
    mov es, ax
    xor si, si
    xor di, di
    mov cx, TAM_TELA
    rep movsb
    pop es
    pop ds
    ret
APRESENTA endp

; Funcao: compor uma vez as duas camadas de montanhas e a pista.
; Entrada: ES quadro, DS dados.
; Saida: BASE_LUNAR guarda as linhas desde Y_LONGE.
PREPARA_BASE proc
    call LIMPAR_QUADRO
    mov ASCII_X, 0
    mov ASCII_Y, Y_LONGE
    mov si, offset TERRENO_LONGE_SPRITE
    mov bx, offset TERRENO_LONGE_PALETA
    mov cx, LARG_TELA
    mov dx, LINHAS_RELEVO
    call DESENHA_SPRITE
    add ASCII_Y, LINHAS_RELEVO
    mov al, TERRENO_LONGE_PALETA[1]
    mov dx, ALT_TELA - Y_LONGE - LINHAS_RELEVO
    call PREENCHER_LINHAS

    mov ASCII_Y, Y_PERTO
    mov si, offset TERRENO_PERTO_SPRITE
    mov bx, offset TERRENO_PERTO_PALETA
    mov dx, LINHAS_RELEVO
    call DESENHA_SPRITE
    add ASCII_Y, LINHAS_RELEVO
    mov al, TERRENO_PERTO_PALETA[1]
    mov dx, ALT_TELA - Y_PERTO - LINHAS_RELEVO
    call PREENCHER_LINHAS

    mov ASCII_Y, Y_SUPERFICIE
    mov al, COR_SUPERFICIE
    mov dx, ALTURA_SUPERFICIE
    call PREENCHER_LINHAS

    mov di, MARCA_PISTA_Y * LARG_TELA
    mov dx, LARG_TELA / MARCA_PISTA_PASSO
    mov al, MARROM
base_marca:
    mov cx, MARCA_PISTA_LARG
    rep stosb
    add di, MARCA_PISTA_PASSO - MARCA_PISTA_LARG
    dec dx
    jnz base_marca

    push ds
    push es
    push ds
    push es
    pop ds
    pop es
    mov si, Y_LONGE * LARG_TELA
    mov di, offset BASE_LUNAR
    mov cx, TAM_RELEVO
    rep movsb
    pop es
    pop ds
    ret
PREPARA_BASE endp

; Funcao: desenhar o fundo ciclico; cada linha tem cauda e inicio.
; Entrada: ROLA_X em 0..LARG_TELA-1, ES quadro.
; Saida: ceu e base lunar compostos, altera registradores de trabalho.
DESENHA_BASE proc
    xor di, di
    mov al, COR_FUNDO
    mov cx, Y_LONGE * LARG_TELA
    rep stosb
    mov bx, offset BASE_LUNAR
    mov bp, ALT_TELA - Y_LONGE
base_linha:
    mov si, bx
    add si, ROLA_X
    mov cx, LARG_TELA
    sub cx, ROLA_X
    rep movsb
    mov si, bx
    mov cx, ROLA_X
    rep movsb
    add bx, LARG_TELA
    dec bp
    jnz base_linha
    ret
DESENHA_BASE endp

; Funcao: medir texto terminado em zero.
; Entrada: DS:SI texto de uma linha.
; Saida: AX quantidade de caracteres; preserva SI.
MEDIR_TEXTO proc
    push si
    xor ax, ax
mede_le:
    cmp byte ptr [si], 0
    je mede_fim
    inc ax
    inc si
    jmp mede_le
mede_fim:
    pop si
    ret
MEDIR_TEXTO endp

; Funcao: converter numero para decimal com zeros a esquerda.
; Entrada: AX valor, CX digitos, DS:DI inicio do destino.
; Saida: grava CX caracteres; altera AX, BX, CX, DX e DI.
FORMATA_DECIMAL proc
    add di, cx
    mov bx, 10
decimal_digito:
    xor dx, dx
    div bx
    add dl, '0'
    dec di
    mov [di], dl
    loop decimal_digito
    ret
FORMATA_DECIMAL endp

; Funcao: desenhar os dois botoes e destacar a opcao selecionada.
; Entrada: OPCAO_SEL, ES quadro.
; Saida: atualiza a faixa dos botoes no quadro.
DESENHA_BOTOES proc
    xor bp, bp
botao_laco:
    mov si, ds:BOTOES_TXT[bp]
    mov ax, ds:BOTOES_Y[bp]
    mov ASCII_Y, ax
    call MEDIR_TEXTO
    add ax, CAIXA_ESPACOS
    mov cx, ax
    add ax, CAIXA_CANTOS
    mov bx, LARGURA
    mul bx
    mov bx, LARG_TELA
    sub bx, ax
    shr bx, 1
    mov ASCII_X, bx
    mov di, offset COR_BOTAO
    mov ax, bp
    shr ax, 1
    cmp al, OPCAO_SEL
    jne botao_moldura
    mov di, offset COR_SELEC
botao_moldura:
    call DESENHAR_CAIXA
    add ASCII_X, (CAIXA_CANTOS + CAIXA_ESPACOS) / 2 * LARGURA
    add ASCII_Y, ALTURA
    mov cx, LARGURA
    mov dx, ALTURA
    call ESCREVER_TEXTO
    add bp, 2
    cmp bp, NUM_OPCOES * 2
    jb botao_laco
    ret
DESENHA_BOTOES endp

; Funcao: avancar e desenhar os quatro objetos ciclicos do menu.
; Entrada: tabela MENU_SPRITES, ES quadro.
; Saida: Xs atualizados; faixa do menu redesenhada.
ANIMA_MENU proc
