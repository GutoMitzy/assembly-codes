LIMPA_OBSTACULOS endp

; Funcao: verificar se ha espaco na entrada direita para um obstaculo.
; Entrada: listas CRATERAS e ROCHAS.
; Saida: CF=1 se a entrada estiver ocupada; preserva SI e CX.
ESPACO_LIVRE proc
    push si
    push cx
    mov si, offset CRATERAS
    mov cx, NUM_OBST
espaco_cratera:
    cmp word ptr [si + O_X], LARG_TELA - DIST_ENTRE_OBST
    jg espaco_ocupado
    add si, TAM_OBST
    loop espaco_cratera
    mov si, offset ROCHAS
    mov cx, NUM_OBST
espaco_rocha:
    cmp word ptr [si + O_X], LARG_TELA - DIST_ENTRE_OBST
    jg espaco_ocupado
    add si, TAM_OBST
    loop espaco_rocha
    clc
    jmp espaco_fim
espaco_ocupado:
    stc
espaco_fim:
    pop cx
    pop si
    ret
ESPACO_LIVRE endp

; Funcao: mover os slots e tentar gerar um obstaculo quando vencer a distancia.
; Entrada: BX descritor de categoria.
; Saida: lista atualizada; altera AX, CX, SI e DI.
ATUALIZA_OBSTACULOS proc
    mov si, [bx + D_SLOTS]
    mov cx, NUM_OBST
obst_move:
    mov ax, [si + O_X]
    cmp ax, SLOT_LIVRE
    je obst_move_prox
    sub ax, VEL_CHAO
    add ax, [bx + D_LARG]
    jg obst_pos_visivel
    mov ax, SLOT_LIVRE
    jmp obst_pos_grava
obst_pos_visivel:
    sub ax, [bx + D_LARG]
obst_pos_grava:
    mov [si + O_X], ax
obst_move_prox:
    add si, TAM_OBST
    loop obst_move

    mov di, [bx + D_PROX]
    cmp word ptr [di], VEL_CHAO
    jbe obst_tenta_criar
    sub word ptr [di], VEL_CHAO
    ret
obst_tenta_criar:
    mov word ptr [di], 0
    call ESPACO_LIVRE
    jc obst_atual_fim
    mov si, [bx + D_SLOTS]
    mov cx, NUM_OBST
obst_procura:
    cmp word ptr [si + O_X], SLOT_LIVRE
    je obst_cria
    add si, TAM_OBST
    loop obst_procura
    ret
obst_cria:
    mov word ptr [si + O_X], LARG_TELA
    mov cx, [bx + D_TIPOS]
    call ALEATORIO
    mov [si + O_TIPO], al
    mov byte ptr [si + O_FLAGS], 0
    mov byte ptr [si + O_VIDAS], 0
    cmp word ptr [bx + D_VIDAS], 0
    je obst_proxima_dist
    push bx
    mov bx, [bx + D_VIDAS]
    xlat
    mov [si + O_VIDAS], al
    pop bx
obst_proxima_dist:
    mov cx, [bx + D_VAR]
    call ALEATORIO
    add ax, [bx + D_DIST]
    mov [di], ax
obst_atual_fim:
    ret
ATUALIZA_OBSTACULOS endp

; Funcao: desenhar todos os obstaculos ativos de uma categoria.
; Entrada: BX descritor, ES quadro.
; Saida: sprites compostos, altera registradores de trabalho.
DESENHA_OBSTACULOS proc
    mov di, [bx + D_SLOTS]
    mov bp, NUM_OBST
desobst_slot:
    mov ax, [di + O_X]
    cmp ax, SLOT_LIVRE
    je desobst_prox
    mov ASCII_X, ax
    mov ax, [bx + D_Y]
    mov ASCII_Y, ax
    xor ax, ax
    mov al, [di + O_TIPO]
    mul word ptr [bx + D_LARG]
    mul word ptr [bx + D_ALT]
    mov si, [bx + D_SPRITE]
    add si, ax
    mov cx, [bx + D_LARG]
    mov dx, [bx + D_ALT]
    push bx
    mov bx, [bx + D_PALETA]
    call DESENHA_SPRITE
    pop bx
desobst_prox:
    add di, TAM_OBST
    dec bp
    jnz desobst_slot
    ret
DESENHA_OBSTACULOS endp

; Funcao: verificar passagem e contato do jipe com os obstaculos.
; Entrada: listas de obstaculos, JIPE_X, JIPE_ALT e IMUNIDADE.
; Saida: CF=1 se colidiu; soma pontos quando termina de ultrapassar.
COLISAO_OBSTACULOS proc
    mov si, offset CRATERAS
    mov cx, NUM_OBST
    xor di, di                        ; 0 = cratera, 1 = rocha
colobst_slot:
    mov dx, [si + O_X]
    cmp dx, SLOT_LIVRE
    jne colobst_ocupado
    jmp colobst_proximo
colobst_ocupado:
    or di, di
    jnz colobst_rocha
    xor bx, bx
    mov bl, [si + O_TIPO]
    shl bx, 1
    xor ax, ax
    mov al, ABERTURAS[bx]
    add ax, dx
    xor bh, bh
    mov bl, ABERTURAS[bx + 1]
    add bx, dx
    mov dx, JIPE_X
    add dx, RODA_INI_JIPE
    mov bp, JIPE_X
    add bp, RODA_FIM_JIPE + 1
    jmp colobst_intervalos

colobst_rocha:
    mov ax, dx
    add ax, MARGEM_ROCHA
    mov bx, dx
    add bx, LARGURA_ROCHA - MARGEM_ROCHA
    mov dx, JIPE_X
    add dx, MARGEM_JIPE_ROCHA
    mov bp, JIPE_X
    add bp, LARGURA_JIPE - MARGEM_JIPE_ROCHA

colobst_intervalos:
    cmp bx, dx
    jle colobst_atras
    cmp ax, bp
    jge colobst_proximo
    or di, di
    jnz colobst_alt_rocha
    cmp JIPE_ALT, 0
    je colobst_contato
    jmp colobst_no_ar
colobst_alt_rocha:
    cmp JIPE_ALT, ALT_LIVRE_ROCHA
    jb colobst_contato
colobst_no_ar:
    or byte ptr [si + O_FLAGS], FLAG_SOBREVOADA
    jmp colobst_proximo

colobst_atras:
    test byte ptr [si + O_FLAGS], FLAG_SOBREVOADA
    jz colobst_proximo
    test byte ptr [si + O_FLAGS], FLAG_PONTUADA
    jnz colobst_proximo
    or byte ptr [si + O_FLAGS], FLAG_PONTUADA
    mov ax, SCORE_CRATERA
    or di, di
    jz colobst_pontos
    mov ax, SCORE_ROCHA
colobst_pontos:
    call SOMAR_SCORE

colobst_proximo:
    add si, TAM_OBST
    dec cx
    jz colobst_fim_tipo
    jmp colobst_slot
colobst_fim_tipo:
    or di, di
    jnz colobst_sem_impacto
    inc di
    mov si, offset ROCHAS
    mov cx, NUM_OBST
    jmp colobst_slot

colobst_contato:
    cmp IMUNIDADE, 0
    jne colobst_proximo
    stc
    ret
colobst_sem_impacto:
    clc
    ret
COLISAO_OBSTACULOS endp

; Funcao: sortear um tipo e tamanho para o proximo grupo.
; Entrada: todos os slots de nave estao livres.
; Saida: ativa 1..NUM_ALIENS slots e recarrega ALIEN_ATRASO.
CRIA_GRUPO_ALIENS proc
    push AX
    push BX
    push CX
    push DX
    push SI
    push DI
    push BP

    ; Sorteia o tipo (0..2) do grupo
    mov CX, TIPOS_NAVE
    call ALEATORIO
    mov GRUPO_TIPO, AX       ; tipo compartilhado por todo o grupo

    ; Sorteia N (1..3)
    mov CX, NUM_ALIENS
    call ALEATORIO
    inc AX
    mov BP, AX               ; BP = N

    xor DI, DI               ; DI = I (0..N-1)
    xor BX, BX               ; BX = I*2

cga_loop:
    ; min_y = (I==0) ? ALIEN_Y_MIN : ALIENS_Y[I-1] + ALIEN_DIST_MIN
    test DI, DI
    jz  cga_first
    mov AX, ALIENS_Y[BX-2]
    add AX, ALIEN_DIST_MIN
    jmp cga_min_ready
cga_first:
    mov AX, ALIEN_Y_MIN
cga_min_ready:
    push AX                  ; guarda min_y (o mul sobrescreve DX)

    mov AX, BP
    sub AX, DI
    dec AX                   ; AX = N-1-I
    mov CX, ALIEN_DIST_MIN
    mul CX                   ; AX = (N-1-I) * 30 (DX = 0)
    mov CX, ALIEN_Y_MAX
    sub CX, AX               ; CX = max_y

    pop DX                   ; DX = min_y
    sub CX, DX
    inc CX                   ; CX = range = max_y - min_y + 1

    call ALEATORIO           ; AX = 0..range-1 (preserva BX, DX, SI, DI, BP)
    add AX, DX               ; AX = Y valido

    mov ALIENS_Y[BX], AX
    mov word ptr ALIENS_X[BX], LARG_TELA
    mov word ptr ALIENS_ATIVO[BX], 1

    add BX, 2
    inc DI
    cmp DI, BP
    jb  cga_loop

    mov ALIEN_ATRASO, ALIEN_SPAWN_DELAY

    pop BP
    pop DI
    pop SI
    pop DX
    pop CX
    pop BX
    pop AX
    ret
CRIA_GRUPO_ALIENS endp

; Funcao: atualizar um grupo de naves e aguardar ate o ultimo slot sair.
; Entrada: ALIENS_ATIVO, ALIENS_X e ALIEN_ATRASO.
; Saida: naves movidas ou grupo novo; altera AX e BX.
ATUALIZA_ALIENS proc
    xor bx, bx
alien_existe:
    cmp ALIENS_ATIVO[bx], 0
    jne alien_tem_grupo
    add bx, 2
    cmp bx, NUM_ALIENS * 2
    jb alien_existe
    dec ALIEN_ATRASO
    jnz alien_atual_fim
    call CRIA_GRUPO_ALIENS
    ret

alien_tem_grupo:
    xor bx, bx
alien_move:
    cmp ALIENS_ATIVO[bx], 0
    je alien_move_prox
    sub ALIENS_X[bx], VEL_ALIEN
    cmp ALIENS_X[bx], -LARGURA_NAVE
    jg alien_move_prox
    mov ALIENS_ATIVO[bx], 0
alien_move_prox:
    add bx, 2
    cmp bx, NUM_ALIENS * 2
    jb alien_move
alien_atual_fim:
    ret
ATUALIZA_ALIENS endp

