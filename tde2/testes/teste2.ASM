    mov dx, [si + T_ALT]
    mov al, [si + T_COR]
    call PREENCHER_LINHAS
desenha_tiro_fim:
    ret
DESENHA_TIRO endp

; Funcao: testar sobreposicao entre tiro ativo e um retangulo.
; Entrada: DS:SI tiro; AX alvo X, BX alvo Y, CX largura, DX altura.
; Saida: CF=1 se ha intersecao; preserva DI e parametros.
ACERTO_TIRO proc
    cmp word ptr [si + T_ATIVO], 0
    je acerto_nao
    push di
    mov di, ax
    add di, cx
    cmp [si + T_X], di
    jge acerto_separa
    mov di, [si + T_X]
    add di, [si + T_LARG]
    cmp di, ax
    jle acerto_separa
    mov di, bx
    add di, dx
    cmp [si + T_Y], di
    jge acerto_separa
    mov di, [si + T_Y]
    add di, [si + T_ALT]
    cmp di, bx
    jle acerto_separa
    pop di
    stc
    ret
acerto_separa:
    pop di
acerto_nao:
    clc
    ret
ACERTO_TIRO endp

; Funcao: resolver o primeiro impacto do tiro frontal contra uma rocha.
; Entrada: TIRO_FRENTE e ROCHAS.
; Saida: tiro consumido, resistencia reduzida e pontos se destruiu.
TIRO_CONTRA_ROCHAS proc
    mov si, offset TIRO_FRENTE
    cmp word ptr [si + T_ATIVO], 0
    je tiro_rocha_fim
    mov di, offset ROCHAS
    mov bp, NUM_OBST
tiro_rocha_slot:
    mov ax, [di + O_X]
    cmp ax, SLOT_LIVRE
    je tiro_rocha_prox
    mov bx, Y_ROCHA
    mov cx, LARGURA_ROCHA
    mov dx, ALTURA_ROCHA
    call ACERTO_TIRO
    jc tiro_rocha_acerta
tiro_rocha_prox:
    add di, TAM_OBST
    dec bp
    jnz tiro_rocha_slot
    ret
tiro_rocha_acerta:
    mov word ptr [si + T_ATIVO], 0
    cmp byte ptr [di + O_VIDAS], ROCHA_INDESTRUTIVEL
    je tiro_rocha_fim
    dec byte ptr [di + O_VIDAS]
    jnz tiro_rocha_fim
    mov word ptr [di + O_X], SLOT_LIVRE
    mov ax, SCORE_ROCHA
    call SOMAR_SCORE
tiro_rocha_fim:
    ret
TIRO_CONTRA_ROCHAS endp

; Funcao: resolver o primeiro impacto do tiro superior contra uma nave.
; Entrada: TIRO_CIMA e slots de naves.
; Saida: tiro e nave desativados e pontos somados quando ha impacto.
TIRO_CONTRA_ALIENS proc
    mov si, offset TIRO_CIMA
    cmp word ptr [si + T_ATIVO], 0
    je tiro_alien_fim
    xor di, di
tiro_alien_slot:
    cmp ALIENS_ATIVO[di], 0
    je tiro_alien_prox
    mov ax, ALIENS_X[di]
    mov bx, ALIENS_Y[di]
    mov cx, LARGURA_NAVE
    mov dx, ALTURA_NAVE
    call ACERTO_TIRO
    jc tiro_alien_acerta
tiro_alien_prox:
    add di, 2
    cmp di, NUM_ALIENS * 2
    jb tiro_alien_slot
    ret
tiro_alien_acerta:
    mov word ptr [si + T_ATIVO], 0
    mov ALIENS_ATIVO[di], 0
    mov ax, SCORE_ALIEN
    call SOMAR_SCORE
tiro_alien_fim:
    ret
TIRO_CONTRA_ALIENS endp

; Funcao: atualizar projeteis inimigos e resolver acertos no jipe.
; Entrada: TIROS_ALIENS, posicao do jipe e IMUNIDADE.
; Saida: CF=1 se houve acerto capaz de tirar vida.
TIROS_CONTRA_JIPE proc
    mov si, offset TIROS_ALIENS
    xor bp, bp
tiro_jipe_slot:
    call ATUALIZA_TIRO
    mov ax, JIPE_X
    mov bx, JIPE_Y
    sub bx, JIPE_ALT
    mov cx, LARGURA_JIPE
    mov dx, ALTURA_JIPE
    call ACERTO_TIRO
    jnc tiro_jipe_prox
    mov word ptr [si + T_ATIVO], 0
    cmp IMUNIDADE, 0
    jne tiro_jipe_prox
    inc bp
tiro_jipe_prox:
    add si, TAM_TIRO
    cmp si, offset TIROS_FIM
    jb tiro_jipe_slot
    neg bp                             ; CF=1 se BP era diferente de zero
    ret
TIROS_CONTRA_JIPE endp

; Funcao: compor um quadro da partida do fundo para a frente.
; Entrada: estado completo da partida, ES quadro.
; Saida: quadro pronto para APRESENTA.
DESENHA_PARTIDA proc
    call DESENHA_BASE
    mov bx, offset DESC_CRATERAS
    call DESENHA_OBSTACULOS
    mov bx, offset DESC_ROCHAS
    call DESENHA_OBSTACULOS
    call DESENHA_ALIENS
    mov si, offset TIRO_CIMA
    call DESENHA_TIRO
    mov si, offset TIRO_FRENTE
    call DESENHA_TIRO
    mov si, offset TIROS_ALIENS
desenha_partida_tiro:
    call DESENHA_TIRO
    add si, TAM_TIRO
    cmp si, offset TIROS_FIM
    jb desenha_partida_tiro

    mov ax, JIPE_X
    mov ASCII_X, ax
    mov ax, JIPE_Y
    sub ax, JIPE_ALT
    mov ASCII_Y, ax
    mov si, offset JIPE_SPRITE
    mov bx, offset JIPE_PALETA
    mov cx, LARGURA_JIPE
    mov dx, ALTURA_JIPE
    call DESENHA_SPRITE
    call DESENHA_STATUS
    ret
DESENHA_PARTIDA endp

; Funcao: iniciar uma partida e preparar listas, HUD e relogio.
; Entrada: ES quadro, DS dados.
; Saida: estado de partida inicializado.
NOVA_PARTIDA proc
    mov ax, X_INICIO_JIPE
    call POSICIONA_JIPE
    mov IMUNIDADE, 0
    mov PONTOS, 0
    mov VIDAS, VIDAS_INICIAIS
    mov ENCERROU, 0
    mov ROLA_X, 0
    mov TEMPO_RESTANTE, TEMPO_PARTIDA
    mov TICK_ACUM, 0
    mov FRACAO_SEGUNDO, 0
    xor ah, ah
    int 1Ah
    mov TICK_ANT_BAIXO, dx
    mov TICK_ANT_ALTO, cx
    xor dx, cx
    jnz nova_semente
    inc dx
nova_semente:
    mov SEMENTE, dx

    mov bx, offset DESC_CRATERAS
    call LIMPA_OBSTACULOS
    mov bx, offset DESC_ROCHAS
    call LIMPA_OBSTACULOS
    mov cx, DIST_VAR_CRATERA
    call ALEATORIO
    mov CRATERA_PROX, ax
    mov cx, DIST_VAR_ROCHA
    call ALEATORIO
    add ax, ATRASO_PRIMEIRA_ROCHA
    mov ROCHA_PROX, ax

    mov word ptr TIRO_CIMA[T_ATIVO], 0
    mov word ptr TIRO_FRENTE[T_ATIVO], 0
    mov ALIEN_ATRASO, ALIEN_SPAWN_DELAY
    xor bx, bx
    mov si, offset TIROS_ALIENS
nova_slot_alien:
    mov ALIENS_ATIVO[bx], 0
    mov word ptr [si + T_ATIVO], 0
    mov word ptr [si + T_LIM], Y_SUPERFICIE - ALT_TIRO_ALIEN + 1
    mov word ptr [si + T_DX], 0
    mov word ptr [si + T_DY], VEL_TIRO_ALIEN
    mov word ptr [si + T_LARG], LARG_TIRO_ALIEN
    mov word ptr [si + T_ALT], ALT_TIRO_ALIEN
    mov word ptr [si + T_COR], BRANCO
    add bx, 2
    add si, TAM_TIRO
    cmp bx, NUM_ALIENS * 2
    jb nova_slot_alien
    ret
NOVA_PARTIDA endp

; Funcao: rodar a partida, da entrada ao quadro, ate tempo, vidas ou Esc.
; Entrada: partida ja inicializada.
; Saida: PONTOS contem o resultado final.
JOGA_PARTIDA proc
partida_quadro:
    call ATUALIZA_TEMPO
    cmp TEMPO_RESTANTE, 0
    je partida_fim
    call ENTRADA_JOGO
    cmp ENCERROU, 0
    jne partida_fim
    call ATUALIZA_SALTO

    add ROLA_X, VEL_CHAO
    cmp ROLA_X, LARG_TELA
    jb partida_rolou
    sub ROLA_X, LARG_TELA
partida_rolou:
    mov bx, offset DESC_CRATERAS
    call ATUALIZA_OBSTACULOS
    mov bx, offset DESC_ROCHAS
    call ATUALIZA_OBSTACULOS
    call ATUALIZA_ALIENS
    mov si, offset TIRO_CIMA
    call ATUALIZA_TIRO
    mov si, offset TIRO_FRENTE
    call ATUALIZA_TIRO
    call TIRO_CONTRA_ROCHAS
    call TIRO_CONTRA_ALIENS
    call ATIRA_ALIENS
    call TIROS_CONTRA_JIPE
    jc partida_perde
    call COLISAO_OBSTACULOS
    jnc partida_desenha
partida_perde:
    call PERDE_VIDA
    cmp VIDAS, 0
    je partida_fim
partida_desenha:
    call DESENHA_PARTIDA
    call APRESENTA
    jmp partida_quadro
partida_fim:
    ret
JOGA_PARTIDA endp

start:
    mov ax, @data
    mov ds, ax
    mov ax, MODO_VGA
    int 10h
    mov ax, SEG QUADRO
    mov es, ax
    cld
    call PREPARA_BASE
fluxo_menu:
    call MENU_INICIAL
    cmp OPCAO_SEL, OPCAO_SAIR
    je fluxo_sai
    call NOVA_PARTIDA
    call JOGA_PARTIDA
    call GAME_OVER
    jmp fluxo_menu
fluxo_sai:
    mov ax, MODO_TEXTO
    int 10h
    mov ax, 4C00h
    int 21h

end start
