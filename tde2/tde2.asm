; ---------------------------------------------------------------------
; DESENHA_CARACTERE: desenha um glifo da fonte bitmap na VRAM
; Entrada: AL = ?ndice do glifo na tabela
;          ASCII_X, ASCII_Y = posi??o do canto superior esquerdo
;          COR_ATUAL = cor; ES = 0A000H
; ---------------------------------------------------------------------
DESENHA_CARACTERE proc
    push AX
    push BX
    push CX
    push DX
    push SI
    push DI
    push BP

    xor AH, AH                               ; AX = ?ndice do glifo
    shl AX, 3                                ; AX = ?ndice * 8
    mov SI, offset FONTE_GLYPHS
    add SI, AX                               ; SI = glifo

    mov AX, ASCII_Y
    mov BX, LARG_TELA
    mul BX                                   ; AX = Y * 320
    add AX, ASCII_X
    mov BH, [DI + 1]                         ; BH = cor (entrada 1 da paleta em DI)
    mov DI, AX                               ; DI = Y * 320 + X

    mov AL, BH                               ; AL = cor
    mov BP, ALTURA                           ; contador de linhas
proxima_linha:
    mov BL, [SI]                             ; BL = linha do glifo
    inc SI
    mov CX, LARGURA                          ; 5 colunas

proximo_pixel:
    test BL, 10H                             ; bit 4 = pixel mais ? esquerda
    jz   pixel_vazio
    stosb                                    ; ES:[DI] = AL, DI = DI + 1
    jmp  proximo_bit

pixel_vazio:
    inc DI                                   ; pula o pixel sem pintar

proximo_bit:
    shl BL, 1
    loop proximo_pixel

    add DI, LARG_TELA - LARGURA              ; desce uma linha, mesma coluna inicial
    dec BP
    jnz proxima_linha

    pop BP
    pop DI
    pop SI
    pop DX
    pop CX
    pop BX
    pop AX
    ret
DESENHA_CARACTERE endp

