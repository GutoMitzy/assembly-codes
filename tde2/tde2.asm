; ---------------------------------------------------------------------
; DESENHAR_BOTOES: desenha os botoes, anima os sprites enquanto espera
; e atualiza OPCAO_SEL conforme as setas.
; ---------------------------------------------------------------------
DESENHAR_BOTOES proc
    push AX
    push BX
    push CX
    push DX
    push SI
    push DI
    push BP

botoes_redesenha:
    xor BP, BP               ; BP = indice da opcao

botoes_proximo:
    mov DI, offset COR_BOTAO
    mov AX, BP
    cmp AL, OPCAO_SEL
    jne botoes_cor
    mov DI, offset COR_SELEC

botoes_cor:
    mov BX, BP
    shl BX, 1
    mov SI, BOTOES_TXT[BX]
    mov DX, BOTOES_Y[BX]
    mov BTN_TXT, SI
    mov BTN_Y, DX

    xor CX, CX               ; conta caracteres
    mov BX, SI
botoes_conta:
    cmp byte ptr [BX], 0
    je  botoes_fim_conta
    inc BX
    inc CX
    jmp botoes_conta

botoes_fim_conta:
    mov AX, CX
    add AX, 4
    mov BX, LARGURA
    mul BX                   ; AX = largura total em px
    mov BX, AX
    mov AX, LARG_TELA
    sub AX, BX
    shr AX, 1                ; AX = X centralizado
    mov BTN_X, AX

    add CX, 2
    mov AX, BTN_X
    mov ASCII_X, AX
    mov AX, BTN_Y
    mov ASCII_Y, AX
    call DESENHAR_CAIXA

    mov AX, BTN_X
    add AX, 2 * LARGURA
    mov ASCII_X, AX
    mov AX, BTN_Y
    add AX, ALTURA
    mov ASCII_Y, AX
    mov CX, LARGURA
    mov DX, ALTURA
    mov SI, BTN_TXT
    call ESCREVER_TEXTO

    inc BP
    cmp BP, NUM_OPCOES
    jae botoes_tecla
    jmp botoes_proximo

botoes_tecla:
    call ESPERA_RETRACO
    mov AX, 2
    call MOVER_SPRITES_MENU

    mov AH, 01H
    int 16H                  ; tecla disponivel?
    jz  botoes_tecla
    mov AH, 00H
    int 16H
    cmp AH, 48H              ; seta para cima
    je  botoes_cima
    cmp AH, 50H              ; seta para baixo
    je  botoes_baixo
    cmp AL, 13               ; Enter
    je  botoes_enter
    jmp botoes_tecla

botoes_cima:
    cmp OPCAO_SEL, 0
    je  botoes_tecla
    dec OPCAO_SEL
    jmp botoes_redesenha

botoes_baixo:
    cmp OPCAO_SEL, NUM_OPCOES - 1
    jae botoes_tecla
    inc OPCAO_SEL
    jmp botoes_redesenha

botoes_enter:
    pop BP
    pop DI
    pop SI
    pop DX
    pop CX
    pop BX
    pop AX
    ret
DESENHAR_BOTOES endp

