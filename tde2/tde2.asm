; ---------------------------------------------------------------------
; SOMAR_SCORE: soma um valor a SCORE_INICIAL (max 9999) e atualiza
; a barra de status.
; Entrada: AX = valor a somar; ES = 0A000H
; ---------------------------------------------------------------------
SOMAR_SCORE proc
    push AX
    push BX
    push CX
    push DX
    push SI

    mov SI, AX               ; SI = incremento
    xor AX, AX
    xor BX, BX

soma_le:                     ; AX = numero lido dos 4 digitos
    mov CX, 10
    mul CX
    mov CL, SCORE_INICIAL[BX]
    sub CL, '0'
    xor CH, CH
    add AX, CX
    inc BX
    cmp BX, 4
    jb  soma_le

    add AX, SI
    cmp AX, 9999
    jbe soma_converte
    mov AX, 9999

soma_converte:
    mov BX, 3                ; escreve do menos significativo
    mov CX, 10

soma_escreve:
    xor DX, DX
    div CX
    add DL, '0'
    mov SCORE_INICIAL[BX], DL
    dec BX
    jns soma_escreve

    call DESENHA_SCORE

    pop SI
    pop DX
    pop CX
    pop BX
    pop AX
    ret
SOMAR_SCORE endp

