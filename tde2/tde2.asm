; ---------------------------------------------------------------------
; ASCII_PARA_INDICE: converte um caractere ASCII no ?ndice do glifo
;   (min?scula vira mai?scula; desconhecido vira espa?o)
; Entrada: AL = caractere ASCII
; Sa?da:   AL = ?ndice do glifo (BX e CX preservados)
; ---------------------------------------------------------------------
ASCII_PARA_INDICE proc
    push BX
    push CX

    cmp AL, 'a'                              ; min?scula vira mai?scula
    jb  procura
    cmp AL, 'z'
    ja  procura
    sub AL, 20H

procura:
    mov BX, offset FONTE_CHARS
    mov CX, NUM_GLYPHS

procura_loop:
    cmp AL, [BX]
    je  achou
    inc BX
    loop procura_loop

    mov AL, G_ESPACO                         ; n?o existe na fonte: espa?o
    jmp fim_conversao

achou:
    sub BX, offset FONTE_CHARS               ; BX = ?ndice
    mov AL, BL

