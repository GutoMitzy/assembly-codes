; START
start:
    mov AX, @data
    mov DS, AX

    mov AX, 0A000H
    mov ES, AX                               ; ES = segmento da VRAM
    cld                                      ; SI/DI incrementam

    call MODO_VIDEO
menu:
    ;call LIMPAR_TELA
    call MENU_INICIAL                        ; t?tulo + menu: define OPCAO_SEL
    cmp OPCAO_SEL, 0
    jne fim_programa                         ; 1 = Sair
    call INICIA_JOGO                         ; 0 = Jogar
    jmp menu

fim_programa:
    mov AX, 0003H
    int 10H                                  ; volta ao modo texto
    mov AX, 4C00H
    int 21H                                  ; encerra

end start