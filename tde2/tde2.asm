    mov ASCII_X, 0
    mov ASCII_Y, Y_LONGE
    mov SI, offset TERRENO_LONGE_SPRITE
    mov BX, offset TERRENO_LONGE_PALETA
    mov CX, LARG_TELA
    mov DX, LINHAS_ASCII
    call DESENHA_ASCII_PALETA

    add ASCII_Y, LINHAS_ASCII
    mov AL, [TERRENO_LONGE_PALETA + 1]
    mov CX, LARG_TELA
    mov DX, PREENCHE_LONGE
    call PREENCHER_LINHAS

    mov ASCII_X, 0
    mov ASCII_Y, Y_PERTO
    mov SI, offset TERRENO_PERTO_SPRITE
    mov BX, offset TERRENO_PERTO_PALETA
    mov CX, LARG_TELA
    mov DX, LINHAS_ASCII
    call DESENHA_ASCII_PALETA

    add ASCII_Y, LINHAS_ASCII
    mov AL, [TERRENO_PERTO_PALETA + 1]
    mov CX, LARG_TELA
    mov DX, PREENCHE_PERTO
    call PREENCHER_LINHAS

    mov ASCII_Y, Y_SUPERFICIE
    mov AL, COR_SUPERFICIE
    mov CX, LARG_TELA
    mov DX, ALTURA_SUPERFICIE
    call PREENCHER_LINHAS

    mov ASCII_X, 10
    sub ASCII_Y, ALTURA_JIPE
    mov SI, offset JIPE_SPRITE
    mov BX, offset JIPE_PALETA
    mov CX, LARGURA_JIPE
    mov DX, ALTURA_JIPE
    call DESENHA_ASCII_PALETA

    mov AH, 00H
    int 1AH
    mov TEMPO_DECORRIDO, DX

jogo_loop:
    call ESPERA_RETRACO

    mov BX, offset TIRO_FRENTE
    call VERIFICA_TIRO_ROCHAS
    call VERIFICA_TIRO_CIMA_ALIENS   ; usa TIRO_CIMA internamente e preserva BX

    mov BX, offset TIRO_CIMA
    call ATUALIZA_TIRO
    mov BX, offset TIRO_FRENTE
    call ATUALIZA_TIRO
    call ATUALIZA_TIROS_ALIENS       ; define ALIEN_HIT_FLAG

    call ROLA_CRATERAS               ; define PASSO_CHAO
    call ROLA_ROCHAS
    call ROLA_ALIENS
    call ATIRA_ALIENS

    call VERIFICA_SALTO_CRATERAS
    jc  colidiu
    call VERIFICA_ROCHAS
    jc  colidiu
    cmp ALIEN_HIT_FLAG, 0
    je  sem_colisao                  ; nenhum tiro alienigena acertou o jipe

colidiu:
    call DEC_CORACAO                 ; (resto igual: reinicia_jogo, pausa_colisao...)
    jnc reinicia_jogo
    jmp jogo_fim

reinicia_jogo:
    mov CX, 40               ; ~0,7s de pausa
pausa_colisao:
    call ESPERA_RETRACO
    loop pausa_colisao
    jmp inicio_jogo

sem_colisao:
    call CONTAGEM_TEMPO
    cmp AL, 1
    jne verifica_teclado
    cmp TEMPO_INICIAL, 0
    je  jogo_fim
    call ATUALIZA_TEMPO

verifica_teclado:
    mov AH, 01H
    int 16H                  ; tecla disponivel?
    jz  atualiza_jipe
    mov AH, 00H
    int 16H
    cmp AL, 1BH              ; Esc
    jne verifica_espaco
    jmp jogo_fim

verifica_espaco:
    cmp AL, 20H              ; espaco: atira
    jne verifica_salto
    call DISPARAR

verifica_salto:
    cmp AH, 48H              ; seta para cima: salta
    jne atualiza_jipe
    cmp SALTO_FASE, 0
    jne atualiza_jipe
    mov SALTO_FASE, 1

atualiza_jipe:
    mov JIPE_VEL, 0
    cmp TECLA_ESQ, 1
    jne verifica_direita
    mov JIPE_VEL, -1

verifica_direita:
    cmp TECLA_DIR, 1
    jne move_jipe
    mov JIPE_VEL, 2

move_jipe:
    ; sem SALTO_VX: no ar sem input, JIPE_VEL = 0 (jipe fica parado
    ; horizontalmente; a fase de topo espera a superficie rolar).
    cmp JIPE_VEL, 0
    jne move_jipe_exec
    cmp SALTO_FASE, 0
    je  jogo_volta           ; parado no chao: nada a redesenhar

move_jipe_exec:
    mov AL, [TERRENO_PERTO_PALETA + 1]
    mov FUNDO_COR, AL
    mov AX, JIPE_VEL
    call MOVER_JIPE

jogo_volta:
    jmp jogo_loop

jogo_fim:
    ret
INICIA_JOGO endp

; ---------------------------------------------------------------------
; start: entrypoint. Configura segmentos, instala handler de teclado,
; alterna entre menu e partidas ate o jogador escolher "Sair".
; ---------------------------------------------------------------------
start:
    mov AX, @data
    mov DS, AX

    mov AX, 0A000H
    mov ES, AX
    cld

    mov AX, 3509H            ; salva handler anterior da INT 09h
    int 21H
    mov OLD_INT09_OFF, BX
    mov OLD_INT09_SEG, ES

    push DS
    mov DX, offset TRATA_TECLADO
    mov AX, SEG TRATA_TECLADO
    mov DS, AX
    mov AX, 2509H            ; instala TRATA_TECLADO
    int 21H
    pop DS

    call MODO_VIDEO

menu:
    call LIMPAR_TELA
    call MENU_INICIAL
    cmp OPCAO_SEL, 0
    jne fim_programa         ; 1 = Sair
    call INICIA_ALEATORIO
    call NOVO_JOGO
    call INICIA_JOGO
    call GAME_OVER
    jmp menu

fim_programa:
    mov AX, 0003H            ; volta ao modo texto
    int 10H
    mov AX, 4C00H
    int 21H                  ; encerra

end start