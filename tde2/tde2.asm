; ---------------------------------------------------------------------
; ESCREVER_TEXTO: desenha um texto de uma ou varias linhas pixel a
;   pixel (CR ignorado, LF volta ao X inicial e desce uma linha,
;   0 encerra)
; Entrada: DS:SI = endereco da string terminada em 0
;          ASCII_X, ASCII_Y = posicao inicial
;          DI = endereco da paleta de cor; ES = 0A000H
;          CX = avanco em X por caractere
;          DX = avanco em Y por linha
; Saida:   ASCII_X, ASCII_Y alterados; AX, BX e SI preservados
; ---------------------------------------------------------------------
ESCREVER_TEXTO proc
    push AX
    push BX
    push SI

    mov BX, ASCII_X                          ; BX = X inicial (para o LF)

texto_exibe:
    lodsb                                    ; AL = DS:[SI], SI = SI + 1
    cmp AL, 0
    je  texto_fim
    cmp AL, 13                               ; CR: ignora
    je  texto_exibe
    cmp AL, 10                               ; LF: proxima linha
    je  texto_nova_linha

    call ASCII_PARA_INDICE                   ; AL = indice do glifo
    call DESENHA_CARACTERE                   ; preserva todos os registradores
    add ASCII_X, CX                          ; avanca uma celula em X
    jmp texto_exibe

texto_nova_linha:
    mov ASCII_X, BX                          ; X volta ao inicial
    add ASCII_Y, DX                          ; desce uma celula em Y
    jmp texto_exibe

texto_fim:
    pop SI
    pop BX
    pop AX
    ret
ESCREVER_TEXTO endp

; ---------------------------------------------------------------------
; DESENHAR_CAIXA: desenha a moldura de 3 linhas de celulas de um
;   botao (cantos, linhas horizontais e verticais), sem o texto
; Entrada: ASCII_X, ASCII_Y = canto superior esquerdo
;          CX = quantidade de celulas do meio (letras + 2)
;          DI = endereco da paleta de cor; ES = 0A000H
; Saida:   ASCII_X, ASCII_Y preservados; todos os registradores
;          preservados
; ---------------------------------------------------------------------
DESENHAR_CAIXA proc
    push AX
    push BX
    push CX
    push DX
    push SI
    push BP

    mov SI, ASCII_X                          ; SI = X inicial de cada linha
    mov DX, CX                               ; DX = celulas do meio
    mov BX, offset CAIXA_GLIFOS              ; BX = glifos da linha atual
    mov BP, 3                                ; 3 linhas de celulas

caixa_linha:
    mov AL, [BX]                             ; glifo da esquerda
    call DESENHA_CARACTERE
    add ASCII_X, LARGURA

    mov AL, [BX + 1]                         ; glifo do meio
    mov CX, DX                               ; CX = repeticoes do meio

caixa_meio:
    call DESENHA_CARACTERE
    add ASCII_X, LARGURA
    loop caixa_meio

    mov AL, [BX + 2]                         ; glifo da direita
    call DESENHA_CARACTERE

    mov ASCII_X, SI                          ; volta ao X inicial
    add ASCII_Y, ALTURA                      ; desce uma linha de celulas
    add BX, 3                                ; proximos 3 glifos da tabela
    dec BP
    jnz caixa_linha

    sub ASCII_Y, 3 * ALTURA                  ; restaura o Y inicial

    pop BP
    pop SI
    pop DX
    pop CX
    pop BX
    pop AX
    ret
DESENHAR_CAIXA endp

; ---------------------------------------------------------------------
; DESENHAR_BOTOES: desenha os botoes do menu (Jogar e Sair) e le o
;   teclado: seta para cima e para baixo trocam a opcao selecionada
;   (destacada com COR_SELEC), Enter confirma e retorna
; Entrada: ES = 0A000H; OPCAO_SEL = opcao inicial selecionada
; Saida:   OPCAO_SEL = opcao escolhida (0 = Jogar, 1 = Sair)
;          todos os registradores preservados
; ---------------------------------------------------------------------
DESENHAR_BOTOES proc
    push AX
    push BX
    push CX
    push DX
    push SI
    push DI
    push BP

botoes_redesenha:
    xor BP, BP                               ; BP = indice da opcao

botoes_proximo:
    mov DI, offset COR_BOTAO                 ; paleta: nao selecionado
    mov AX, BP
    cmp AL, OPCAO_SEL
    jne botoes_cor
    mov DI, offset COR_SELEC                 ; esta e a opcao selecionada

botoes_cor:
    mov BX, BP
    shl BX, 1                                ; BX = indice * 2 (tabelas de words)
    mov SI, BOTOES_TXT[BX]                   ; SI = texto do botao
    mov DX, BOTOES_Y[BX]                     ; DX = Y do botao
    mov BTN_TXT, SI
    mov BTN_Y, DX

    xor CX, CX                               ; CX = quantidade de letras
    mov BX, SI

botoes_conta:
    cmp byte ptr [BX], 0
    je  botoes_fim_conta
    inc BX
    inc CX
    jmp botoes_conta

botoes_fim_conta:
    mov AX, CX
    add AX, 4                                ; celulas totais = letras + 4
    mov BX, LARGURA
    mul BX                                   ; AX = largura do botao em pixels
    mov BX, AX
    mov AX, LARG_TELA
    sub AX, BX
    shr AX, 1                                ; AX = (320 - largura) / 2
    mov BTN_X, AX

    add CX, 2                                ; celulas entre os cantos
    mov AX, BTN_X
    mov ASCII_X, AX
    mov AX, BTN_Y
    mov ASCII_Y, AX
    call DESENHAR_CAIXA

    mov AX, BTN_X                            ; texto na celula 2 da linha do meio
    add AX, 2 * LARGURA
    mov ASCII_X, AX
    mov AX, BTN_Y
    add AX, ALTURA
    mov ASCII_Y, AX
    mov CX, LARGURA
    mov DX, ALTURA
    mov SI, BTN_TXT
    call ESCREVER_TEXTO

    inc BP
    cmp BP, NUM_OPCOES
    jae botoes_tecla                         ; todos desenhados: le o teclado
    jmp botoes_proximo                       ; salto longo: jb direto sairia do alcance

botoes_tecla:
    mov AH, 00H
    int 16H                                  ; AH = scan code, AL = ASCII

    cmp AH, 48H                              ; seta para cima
    je  botoes_cima
    cmp AH, 50H                              ; seta para baixo
    je  botoes_baixo
    cmp AL, 13                               ; Enter
    je  botoes_enter
    jmp botoes_tecla                         ; outra tecla: ignora

botoes_cima:
    cmp OPCAO_SEL, 0                         ; ja na primeira opcao
    je  botoes_tecla
    dec OPCAO_SEL
    jmp botoes_redesenha

botoes_baixo:
    cmp OPCAO_SEL, NUM_OPCOES - 1            ; ja na ultima opcao
    jae botoes_tecla
    inc OPCAO_SEL
    jmp botoes_redesenha

botoes_enter:
    pop BP
    pop DI
    pop SI
    pop DX
    pop CX
    pop BX
    pop AX
    ret
DESENHAR_BOTOES endp

; ---------------------------------------------------------------------
; DESENHA_ASCII_PALETA: desenha um sprite colorido; o valor de cada
;   pixel ? traduzido para uma cor por uma paleta (0 = transparente)
; Entrada: SI = endere?o do sprite (uma linha ap?s a outra)
;          BX = endere?o da paleta (tabela de cores indexada pelo
;               valor do pixel)
;          CX = largura do sprite (colunas)
;          DX = altura do sprite (linhas)
;          ASCII_X, ASCII_Y = canto superior esquerdo na tela
;          ES = 0A000H; DF = 0 (CLD)
; ---------------------------------------------------------------------
DESENHA_ASCII_PALETA proc
    push AX
    push BX
    push CX
    push DX
    push SI
    push DI
    push BP

    mov BP, DX
    mov AX, ASCII_Y
    mov DX, LARG_TELA
    mul DX
    add AX, ASCII_X
    mov DI, AX
    mov DX, CX

paleta_linha:
    mov CX, DX

paleta_pixel:
    lodsb
    sub AL, '0'
    cmp AL, 0
    je  paleta_vazio
    xlat
    stosb
    jmp paleta_proximo

paleta_vazio:
    inc DI

paleta_proximo:
    loop paleta_pixel

    add DI, LARG_TELA
    sub DI, DX
    dec BP
    jnz paleta_linha

    pop BP
    pop DI
    pop SI
    pop DX
    pop CX
    pop BX
    pop AX
    ret
DESENHA_ASCII_PALETA endp

; ---------------------------------------------------------------------
; MENU_INICIAL: desenha o t?tulo do jogo e o menu, e espera o
;   usu?rio escolher uma op??o
; Entrada: ES = 0A000H
; Sa?da:   OPCAO_SEL = op??o escolhida (0 = Jogar, 1 = Sair)
; ---------------------------------------------------------------------
MENU_INICIAL proc
    push AX
    push CX
    push DX
    push SI

    mov DI, offset COR_TITULO            
    mov ASCII_X, X_INICIAL_TITULO            ; posi??o inicial do t?tulo
    mov ASCII_Y, Y_INICIAL_TITULO
    mov CX, LARGURA_TITULO                   ; avan?o em X
    mov DX, ALTURA_TITULO                    ; avan?o em Y
    mov SI, offset TITULO_JOGO
    call ESCREVER_TEXTO

    mov ASCII_X, 110                         ; X do canto superior esquerdo
    mov ASCII_Y, 100                         ; Y do canto superior esquerdo
    mov SI, offset JIPE_SPRITE
    mov BX, offset JIPE_PALETA
    mov CX, LARGURA_JIPE
    mov DX, ALTURA_JIPE
    call DESENHA_ASCII_PALETA

    ; nave 1
    mov ASCII_X, 140
    mov SI, offset NAVES_SPRITE
    mov BX, offset NAVE_PALETA
    mov CX, LARGURA_NAVE
    mov DX, ALTURA_NAVE
    call DESENHA_ASCII_PALETA

    ; nave 2 (BX, CX e DX continuam os mesmos)
    mov ASCII_X, 170
    mov SI, offset NAVES_SPRITE + TAM_NAVE
    call DESENHA_ASCII_PALETA

    ; nave 3
    mov ASCII_X, 200
    mov SI, offset NAVES_SPRITE + 2 * TAM_NAVE
    call DESENHA_ASCII_PALETA

    call DESENHAR_BOTOES

    pop SI
    pop DX
    pop CX
    pop AX
    ret
MENU_INICIAL endp

; ---------------------------------------------------------------------
; INICIA_JOGO: inicializa os elementos do jogo
; ---------------------------------------------------------------------
INICIA_JOGO proc
    call LIMPAR_TELA

    mov ASCII_X, 5
    mov ASCII_Y, 5
    mov SI, CORACOES[4]
    mov BX, offset COR_CORACAO
    mov CX, CORACAO_LARG[4]
    mov DX, ALTURA_CORACAO
    call DESENHA_ASCII_PALETA

    mov ASCII_X, 280
    mov ASCII_Y, 7
    mov SI, offset RELOGIO_SPRITE
    mov BX, offset COR_RELOGIO
    mov CX, LARGURA_RELOGIO
    mov DX, ALTURA_RELOGIO
    call DESENHA_ASCII_PALETA
    
    mov ASCII_X, 0
    mov ASCII_Y, Y_LONGE
    mov SI, offset TERRENO_LONGE_SPRITE
    mov BX, offset TERRENO_LONGE_PALETA
    mov CX, LARG_TELA
    mov DX, LINHAS_ASCII
    call DESENHA_ASCII_PALETA

    add ASCII_Y, LINHAS_ASCII
    mov AL, [TERRENO_LONGE_PALETA + 1]
    mov CX, LARG_TELA
    mov DX, PREENCHE_LONGE
    call PREENCHER_LINHAS

    mov ASCII_X, 0
    mov ASCII_Y, Y_PERTO
    mov SI, offset TERRENO_PERTO_SPRITE
    mov BX, offset TERRENO_PERTO_PALETA
    mov CX, LARG_TELA
    mov DX, LINHAS_ASCII
    call DESENHA_ASCII_PALETA

    add ASCII_Y, LINHAS_ASCII
    mov AL, [TERRENO_PERTO_PALETA + 1]
    mov CX, LARG_TELA
    mov DX, PREENCHE_PERTO
    call PREENCHER_LINHAS
    
    mov ASCII_Y, Y_SUPERFICIE
    mov AL, COR_SUPERFICIE
    mov CX, LARG_TELA
    mov DX, ALTURA_SUPERFICIE
    call PREENCHER_LINHAS
    
    mov ASCII_X, 10 
    sub ASCII_Y, ALTURA_JIPE    
    mov SI, offset JIPE_SPRITE
    mov BX, offset JIPE_PALETA
    mov CX, LARGURA_JIPE
    mov DX, ALTURA_JIPE
    call DESENHA_ASCII_PALETA
    
    mov AH, 00H
    int 16H                                  ; espera uma tecla
    
    ret
INICIA_JOGO endp

