; ---------------------------------------------------------------------
; TRATA_TECLADO: handler da INT 09h; rastreia pressionamento/soltura
; das setas. Encadeia com o handler anterior no final.
; ---------------------------------------------------------------------
TRATA_TECLADO proc far
    push AX
    push DS

    mov AX, @data
    mov DS, AX

    in AL, 60H               ; le scan code

    cmp AL, 4BH              ; seta esquerda pressionada
    je tecla_esq_press
    cmp AL, 0CBH             ; seta esquerda solta
    je tecla_esq_solto
    cmp AL, 4DH              ; seta direita pressionada
    je tecla_dir_press
    cmp AL, 0CDH             ; seta direita solta
    je tecla_dir_solto
    jmp teclado_fim

tecla_esq_press:
    mov TECLA_ESQ, 1
    jmp teclado_fim

tecla_esq_solto:
    mov TECLA_ESQ, 0
    jmp teclado_fim

tecla_dir_press:
    mov TECLA_DIR, 1
    jmp teclado_fim

tecla_dir_solto:
    mov TECLA_DIR, 0

teclado_fim:
    pop DS
    pop AX

    push OLD_INT09_SEG
    push OLD_INT09_OFF
    retf                     ; encadeia com o handler anterior
TRATA_TECLADO endp

; ---------------------------------------------------------------------
; ATUALIZA_TIRO: avanca 1 quadro do tiro: restaura fundo, move, e
; desenha; desativa ao atingir T_LIM.
; Entrada: BX = registro do tiro; ES = 0A000H
; ---------------------------------------------------------------------
ATUALIZA_TIRO proc
    push AX
    push CX
    push DX
    push SI

    cmp word ptr [BX + T_ATIVO], 0
    je  tiro_fim

    mov AX, [BX + T_X]
    mov ASCII_X, AX
    mov AX, [BX + T_Y]
    mov ASCII_Y, AX
    lea SI, [BX + T_FUNDO]
    mov CX, [BX + T_LARG]
    mov DX, [BX + T_ALT]
    mov AL, 1                ; restaura fundo
    call COPIA_FUNDO

    mov AX, [BX + T_X]
    add AX, [BX + T_DX]
    mov [BX + T_X], AX
    mov AX, [BX + T_Y]
    add AX, [BX + T_DY]
    mov [BX + T_Y], AX

    cmp word ptr [BX + T_DX], 0
    je  tiro_vertical

    mov AX, [BX + T_X]       ; tiro frontal
    cmp AX, [BX + T_LIM]
    jge tiro_desativa
    jmp tiro_desenha

tiro_vertical:
    mov AX, [BX + T_Y]       ; tiro superior
    cmp AX, [BX + T_LIM]
    jle tiro_desativa

tiro_desenha:
    call DESENHA_TIRO
    jmp tiro_fim

tiro_desativa:
    mov word ptr [BX + T_ATIVO], 0

tiro_fim:
    pop SI
    pop DX
    pop CX
    pop AX
    ret
ATUALIZA_TIRO endp

; ---------------------------------------------------------------------
; DISPARAR: dispara os dois canhoes (frontal e superior), cada um se
; o tiro anterior ja tiver sumido.
; Entrada: JIPE_X, JIPE_Y, JIPE_ALT; ES = 0A000H
; ---------------------------------------------------------------------
DISPARAR proc
    push AX
    push BX

    mov BX, offset TIRO_CIMA
    cmp word ptr [BX + T_ATIVO], 0
    jne disparar_frente
    mov AX, JIPE_X
    add AX, CANHAO_CIMA_X
    mov [BX + T_X], AX
    mov AX, JIPE_Y - ALT_TIRO_CIMA
    sub AX, JIPE_ALT
    mov [BX + T_Y], AX
    mov word ptr [BX + T_ATIVO], 1
    call DESENHA_TIRO

disparar_frente:
    mov BX, offset TIRO_FRENTE
    cmp word ptr [BX + T_ATIVO], 0
    jne disparar_fim
    mov AX, JIPE_X
    add AX, LARGURA_JIPE + 2         ; 2 px de folga (jipe anda ate 2 px/q)
    mov [BX + T_X], AX
    add AX, ALCANCE_TIRO
    mov [BX + T_LIM], AX
    mov AX, JIPE_Y + CANHAO_FRENTE_Y
    sub AX, JIPE_ALT
    mov [BX + T_Y], AX
    mov word ptr [BX + T_ATIVO], 1
    call DESENHA_TIRO

disparar_fim:
    pop BX
    pop AX
    ret
DISPARAR endp

; ---------------------------------------------------------------------
; ALEATORIO: PRNG xorshift de 16 bits (periodo 65535, semente != 0).
; Entrada: CX = faixa (>= 1)
; Saida:   AX = valor 0..CX-1
; ---------------------------------------------------------------------
ALEATORIO proc
    push DX
    push CX

    mov AX, SEMENTE
    mov DX, AX
    mov CL, 7
    shl DX, CL
    xor AX, DX               ; x ^= x << 7
    mov DX, AX
    mov CL, 9
    shr DX, CL
    xor AX, DX               ; x ^= x >> 9
    mov DX, AX
    mov CL, 8
    shl DX, CL
    xor AX, DX               ; x ^= x << 8
    mov SEMENTE, AX

    pop CX
    xor DX, DX
    div CX                   ; DX = AX mod CX
    mov AX, DX

    pop DX
    ret
ALEATORIO endp

; ---------------------------------------------------------------------
; INICIA_ALEATORIO: mistura ticks do BIOS com o timer 8253 para gerar
; uma semente diferente a cada chamada.
; ---------------------------------------------------------------------
INICIA_ALEATORIO proc
    push AX
    push CX
    push DX

    mov AH, 00H
    int 1AH                  ; CX:DX = ticks
    xor DX, CX
    xor AL, AL
    out 43H, AL
    in  AL, 40H
    mov AH, AL
    in  AL, 40H              ; AX = contador do timer
    xor AX, DX
    jnz semente_ok
    mov AX, 0ACE1H           ; semente nao pode ser 0
semente_ok:
    mov SEMENTE, AX

    pop DX
    pop CX
    pop AX
    ret
INICIA_ALEATORIO endp

; ---------------------------------------------------------------------
; ACHA_BURACO: localiza as colunas do digito '3' (buraco) no bitmap
; da variacao de cratera.
; Entrada: AL = variacao (0..2)
; Saida:   CF = 0: AL = 1a coluna, AH = ultima coluna com '3'
;          CF = 1: nao ha '3' no bitmap
; ---------------------------------------------------------------------
ACHA_BURACO proc
    push BX
    push DX
    push SI

    xor AH, AH
    mov DX, TAM_CRATERA
    mul DX
    mov SI, offset CRATERAS_SPRITE
    add SI, AX

    mov BH, 0FFH             ; menor coluna com '3'
    xor BL, BL               ; maior coluna com '3'
    mov DL, ALTURA_CRATERA

buraco_linha:
    xor DH, DH

buraco_pixel:
    cmp byte ptr [SI], '3'
    jne buraco_seguinte
    cmp DH, BH
    jae buraco_max
    mov BH, DH
buraco_max:
    cmp DH, BL
    jbe buraco_seguinte
    mov BL, DH

buraco_seguinte:
    inc SI
    inc DH
    cmp DH, LARGURA_CRATERA
    jb  buraco_pixel
    dec DL
    jnz buraco_linha

    cmp BH, 0FFH
    je  buraco_nenhum
    mov AL, BH
    mov AH, BL
    clc
    jmp buraco_fim

buraco_nenhum:
    stc

buraco_fim:
    pop SI
    pop DX
    pop BX
    ret
ACHA_BURACO endp

; ---------------------------------------------------------------------
; VERIFICA_SALTO_CRATERAS: compara as rodas do jipe com as colunas do
; buraco de cada cratera visivel.
;   - roda sobre buraco + jipe no chao  = colisao (CF = 1)
;   - roda sobre buraco + jipe no ar    = marca FLAG_SOBREVOADA
;   - buraco inteiro atras + salto ok   = +SCORE_CRATERA (uma vez)
; ---------------------------------------------------------------------
VERIFICA_SALTO_CRATERAS proc
    push AX
    push BX
    push CX
    push DX
    push SI
    push DI

    xor BX, BX               ; BX = slot * 2

verif_slot:
    mov DI, CRATERAS_X[BX]
    cmp DI, CRATERA_LIVRE
    je  verif_prox
    mov SI, BX
    shr SI, 1                ; SI = slot

    mov AL, CRATERAS_TIPO[SI]
    test AL, FLAG_PONTUADA
    jnz verif_prox
    and AL, MASCARA_TIPO
    call ACHA_BURACO         ; AL = 1a coluna, AH = ultima
    jc  verif_prox

    mov CL, AH
    xor CH, CH
    add CX, DI               ; CX = X fim do buraco
    xor AH, AH
    add AX, DI               ; AX = X inicio do buraco

    cmp CX, JIPE_X
    jl  verif_passou         ; buraco ja atras do jipe

    mov DX, JIPE_X
    add DX, RODA_FIM_JIPE
    cmp AX, DX
    jg  verif_prox           ; buraco ainda a frente

    cmp JIPE_ALT, 0
    jne verif_ar
    stc
    jmp verif_fim

verif_ar:
    or  CRATERAS_TIPO[SI], FLAG_SOBREVOADA
    jmp verif_prox

verif_passou:
    test CRATERAS_TIPO[SI], FLAG_SOBREVOADA
    jz  verif_prox
    or  CRATERAS_TIPO[SI], FLAG_PONTUADA
    mov AX, SCORE_CRATERA
    call SOMAR_SCORE

verif_prox:
    add BX, 2
    cmp BX, NUM_CRATERAS * 2
    jae verif_nada
    jmp verif_slot

verif_nada:
    clc

verif_fim:
    pop DI
    pop SI
    pop DX
    pop CX
    pop BX
    pop AX
    ret
VERIFICA_SALTO_CRATERAS endp

