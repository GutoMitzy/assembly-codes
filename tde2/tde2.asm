; ---------------------------------------------------------------------
; ATUALIZA_SALTO: avanca 1 quadro do salto trapezoidal.
; Fases:
;   0 = chao
;   1 = subindo   (SALTO_VEL px por quadro ate SALTO_ALTURA)
;   2 = topo      (jipe parado; espera a superficie rolar SALTO_TOPO_PX)
;   3 = descendo  (SALTO_VEL px por quadro ate o chao)
; Altera:  JIPE_ALT, SALTO_FASE, SALTO_PX
; ---------------------------------------------------------------------
ATUALIZA_SALTO proc
    cmp SALTO_FASE, 0
    je  salto_fim
    cmp SALTO_FASE, 2
    je  salto_topo
    ja  salto_descida

    ; fase 1: subindo
    mov AX, JIPE_ALT
    add AX, SALTO_VEL
    cmp AX, SALTO_ALTURA
    jl  salto_grava
    mov AX, SALTO_ALTURA
    mov SALTO_FASE, 2
    mov SALTO_PX, 0
    jmp salto_grava

salto_topo:
    ; fase 2: jipe parado; acumula rolagem do cenario
    add SALTO_PX, VEL_CHAO
    cmp SALTO_PX, SALTO_TOPO_PX
    jb  salto_fim
    mov SALTO_FASE, 3
    jmp salto_fim

salto_descida:
    ; fase 3: descendo
    mov AX, JIPE_ALT
    sub AX, SALTO_VEL
    jg  salto_grava
    xor AX, AX
    mov SALTO_FASE, 0

salto_grava:
    mov JIPE_ALT, AX

salto_fim:
    ret
ATUALIZA_SALTO endp

; ---------------------------------------------------------------------
; MOVER_JIPE: apaga, aplica deslocamento horizontal (limitado), avanca
; o salto e redesenha.
; Entrada: AX = deslocamento horizontal (com sinal); ES = 0A000H
; ---------------------------------------------------------------------
MOVER_JIPE proc
    push AX
    push BX
    push CX
    push DX
    push SI

    push AX

    mov AX, JIPE_X
    mov ASCII_X, AX
    mov AX, JIPE_Y
    sub AX, JIPE_ALT
    mov ASCII_Y, AX
    mov AL, FUNDO_COR
    mov CX, LARGURA_JIPE
    mov DX, ALTURA_JIPE
    call APAGAR_SPRITE

    pop AX
    mov BX, JIPE_X
    add BX, AX
    cmp BX, 0
    jl  jipe_bloqueado
    cmp BX, X_MAX_JIPE
    jg  jipe_bloqueado
    mov JIPE_X, BX

jipe_bloqueado:
    call ATUALIZA_SALTO

    mov AX, JIPE_X
    mov ASCII_X, AX
    mov AX, JIPE_Y
    sub AX, JIPE_ALT
    mov ASCII_Y, AX
    mov SI, offset JIPE_SPRITE
    mov BX, offset JIPE_PALETA
    mov CX, LARGURA_JIPE
    mov DX, ALTURA_JIPE
    call DESENHA_SPRITE_RECORTADO

    pop SI
    pop DX
    pop CX
    pop BX
    pop AX
    ret
MOVER_JIPE endp

